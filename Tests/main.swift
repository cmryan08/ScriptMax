var layoutsStaySafe = true
let layoutWords = ["Okay,", "so", "I'm", "using", "103", "existential", "detectives", "Shania", "Twain", "sandwich", "story", "supercalifragilisticexpialidocious"]
for font in [8.0, 12.0, 22.0, 44.0] {
    for position in layoutWords.indices {
        let remaining = Array(layoutWords.dropFirst(position))
        let layout = PromptLayout.fit(words: remaining, maximumWords: 6, width: max(74, font * 7) - 12, preferredSize: font, minimumSize: font * 0.85)
        let shown = layout.lines.joined(separator: " ")
        layoutsStaySafe = layoutsStaySafe && layout.fontSize >= max(8, font * 0.85) && layout.fontSize <= font
            && shown == remaining.prefix(layout.wordCount).joined(separator: " ")
            && layout.lines.count <= 2
            && layout.lines.allSatisfy { PromptLayout.width($0, size: layout.fontSize) <= layout.requiredWidth }
    }
}
expect(layoutsStaySafe, "Every preview preserves script order, fits two lines, and respects font range")

